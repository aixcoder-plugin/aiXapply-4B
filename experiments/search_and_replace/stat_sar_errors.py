#!/usr/bin/env python3
"""
Summarize the SearchAndReplaceError distribution in jsonl files generated by infer_openai_sar.py.

Input: jsonl output from infer_openai_sar.py (one dict per line, including apply_error)
Output: overview + SearchAndReplaceError category distribution + raw message distribution (TopK)

Example:
  python search_and_replace/stat_sar_errors.py \
    --jsonl search_and_replace/predictions/xxx_sar_YYYYmmdd_HHMMSS.jsonl
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any, DefaultDict, Dict, Iterable, Iterator, List, Optional, Tuple


@dataclass(frozen=True)
class ClassifiedError:
    kind: str  # ok | sar | non_sar | jsonl
    category: str
    message: str


def _iter_jsonl(path: Path) -> Iterator[Tuple[int, Dict[str, Any]]]:
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError as e:
                # The jsonl line itself is malformed; treat it as a file-level error.
                yield line_no, {"_jsonl_parse_error": f"{type(e).__name__}: {e}"}
                continue
            if not isinstance(obj, dict):
                yield line_no, {"_jsonl_parse_error": f"Unexpected top-level JSON type: {type(obj).__name__}"}
                continue
            yield line_no, obj


def _classify_apply_error(apply_error: Any) -> ClassifiedError:
    """
    apply_error values written by infer_openai_sar.py:
    - None: success
    - "Empty model output": the model returned no patch (non-SAR apply failure)
    - "Unexpected apply error: ...": an exception other than SearchAndReplaceError
    - any other string: usually derived from SearchAndReplaceError(str(e)), grouped with rules below
    """
    if apply_error is None:
        return ClassifiedError(kind="ok", category="ok", message="")

    msg = str(apply_error).strip()
    if not msg:
        # Rare case: treat an empty string as ok to avoid polluting the distribution.
        return ClassifiedError(kind="ok", category="ok_empty_apply_error", message="")

    if msg == "Empty model output":
        return ClassifiedError(kind="non_sar", category="empty_model_output", message=msg)

    if msg.startswith("Unexpected apply error:"):
        return ClassifiedError(kind="non_sar", category="unexpected_apply_error", message=msg)

    # ---- SearchAndReplaceError categories (from search_and_replace_tool.py) ----
    if msg == "Patch is not valid JSON and no JSON object/array could be extracted.":
        return ClassifiedError(kind="sar", category="patch_invalid_json", message=msg)

    if msg.startswith("Unexpected patch JSON type:"):
        return ClassifiedError(kind="sar", category="patch_unexpected_json_type", message=msg)

    if msg.startswith("Patch item #") and " is not an object:" in msg:
        return ClassifiedError(kind="sar", category="patch_item_not_object", message=msg)

    if msg.startswith("Patch item #") and " must contain oldString and newString." in msg:
        return ClassifiedError(kind="sar", category="patch_item_missing_fields", message=msg)

    if msg == "No changes to apply: oldString and newString are identical.":
        return ClassifiedError(kind="sar", category="no_changes_to_apply", message=msg)

    if msg.startswith("Could not find oldString in the file."):
        return ClassifiedError(kind="sar", category="oldstring_not_found", message=msg)

    if msg.startswith("Found multiple matches for oldString."):
        return ClassifiedError(kind="sar", category="oldstring_multiple_matches", message=msg)

    return ClassifiedError(kind="sar", category="other_sar_error", message=msg)


def _fmt_pct(n: int, total: int) -> str:
    if total <= 0:
        return "0.00%"
    return f"{(100.0 * n / total):.2f}%"


def _print_top(counter: Counter[str], *, total: int, title: str, top_k: int) -> None:
    print()
    print(title)
    print("-" * len(title))
    if not counter:
        print("(empty)")
        return
    for i, (k, v) in enumerate(counter.most_common(top_k), start=1):
        print(f"{i:>2}. {v:>7}  ({_fmt_pct(v, total)})  {k}")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Summarize the SearchAndReplaceError distribution in a SAR jsonl file.")
    p.add_argument("--jsonl", required=True, help="Path to the .jsonl file produced by infer_openai_sar.py.")
    p.add_argument("--top-k", type=int, default=20, help="Number of TopK entries to display (default: 20).")
    p.add_argument(
        "--show-samples",
        type=int,
        default=0,
        help="Optionally print up to N sample indices per SAR category (default: 0).",
    )
    return p.parse_args()


def main() -> None:
    args = parse_args()
    jsonl_path = Path(args.jsonl)
    if not jsonl_path.exists():
        raise FileNotFoundError(f"File not found: {jsonl_path}")

    total = 0
    ok = 0
    sar_total = 0
    non_sar_total = 0
    jsonl_parse_err_total = 0

    sar_by_category: Counter[str] = Counter()
    sar_by_message: Counter[str] = Counter()
    non_sar_by_category: Counter[str] = Counter()
    jsonl_err_by_message: Counter[str] = Counter()

    # Optionally keep a few sample indices per category for debugging.
    samples: DefaultDict[str, List[int]] = defaultdict(list)

    for line_no, obj in _iter_jsonl(jsonl_path):
        total += 1

        if "_jsonl_parse_error" in obj:
            jsonl_parse_err_total += 1
            jsonl_err_by_message[obj["_jsonl_parse_error"]] += 1
            continue

        apply_error = obj.get("apply_error")
        classified = _classify_apply_error(apply_error)

        if classified.kind == "ok":
            ok += 1
            continue

        if classified.kind == "non_sar":
            non_sar_total += 1
            non_sar_by_category[classified.category] += 1
            continue

        if classified.kind == "sar":
            sar_total += 1
            sar_by_category[classified.category] += 1
            sar_by_message[classified.message] += 1
            if args.show_samples > 0:
                idx = obj.get("index")
                if isinstance(idx, int) and len(samples[classified.category]) < args.show_samples:
                    samples[classified.category].append(idx)
            continue

        # This branch should be unreachable.
        non_sar_total += 1
        non_sar_by_category["unknown_kind"] += 1

    print("=== SAR jsonl summary ===")
    print(f"jsonl: {jsonl_path}")
    print(f"total: {total}")
    print(f"ok: {ok} ({_fmt_pct(ok, total)})")
    print(f"sar_error(SearchAndReplaceError): {sar_total} ({_fmt_pct(sar_total, total)})")
    print(f"non_sar_error: {non_sar_total} ({_fmt_pct(non_sar_total, total)})")
    if jsonl_parse_err_total:
        print(f"jsonl_parse_error: {jsonl_parse_err_total} ({_fmt_pct(jsonl_parse_err_total, total)})")

    _print_top(non_sar_by_category, total=total, title="non_sar_error by category (TopK)", top_k=args.top_k)
    if jsonl_parse_err_total:
        _print_top(jsonl_err_by_message, total=total, title="jsonl parse errors by message (TopK)", top_k=args.top_k)

    _print_top(sar_by_category, total=sar_total, title="SearchAndReplaceError by category (TopK)", top_k=args.top_k)
    _print_top(sar_by_message, total=sar_total, title="SearchAndReplaceError by raw message (TopK)", top_k=args.top_k)

    if args.show_samples > 0 and samples:
        print()
        print("samples (per SAR category)")
        print("-------------------------")
        for cat, idxs in sorted(samples.items(), key=lambda kv: (-sar_by_category[kv[0]], kv[0])):
            if idxs:
                print(f"{cat}: {idxs}")


if __name__ == "__main__":
    main()

